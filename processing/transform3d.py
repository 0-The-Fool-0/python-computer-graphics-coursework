def identity_matrix() -> np.ndarray:
    """Возвращает единичную матрицу 4x4."""
    return np.eye(4, dtype=np.float64)


def translation_matrix(tx: float, ty: float, tz: float) -> np.ndarray:
    """Создает матрицу переноса."""
    T = identity_matrix()
    T[0, 3] = tx
    T[1, 3] = ty
    T[2, 3] = tz
    return T


def scaling_matrix(sx: float, sy: float, sz: float) -> np.ndarray:
    """Создает матрицу масштабирования."""
    S = identity_matrix()
    S[0, 0] = sx
    S[1, 1] = sy
    S[2, 2] = sz
    return S


def rotation_x_matrix(angle_rad: float) -> np.ndarray:
    """Создает матрицу вращения вокруг оси X."""
    c = math.cos(angle_rad)
    s = math.sin(angle_rad)
    R = identity_matrix()
    R[1, 1] = c
    R[1, 2] = -s
    R[2, 1] = s
    R[2, 2] = c
    return R


def rotation_y_matrix(angle_rad: float) -> np.ndarray:
    """Создает матрицу вращения вокруг оси Y."""
    c = math.cos(angle_rad)
    s = math.sin(angle_rad)
    R = identity_matrix()
    R[0, 0] = c
    R[0, 2] = s
    R[2, 0] = -s
    R[2, 2] = c
    return R


def rotation_z_matrix(angle_rad: float) -> np.ndarray:
    """Создает матрицу вращения вокруг оси Z."""
    c = math.cos(angle_rad)
    s = math.sin(angle_rad)
    R = identity_matrix()
    R[0, 0] = c
    R[0, 1] = -s
    R[1, 0] = s
    R[1, 1] = c
    return R


def rotation_around_axis_matrix(axis: Point3D, angle_rad: float) -> np.ndarray:
    """
    Создает матрицу вращения вокруг произвольной оси.
    Использует формулу Родригеса.
    """
    ax, ay, az = axis
    length = math.sqrt(ax**2 + ay**2 + az**2)
    if length < 1e-10:
        return identity_matrix()
    
    # Нормализуем ось
    ax /= length
    ay /= length
    az /= length
    
    c = math.cos(angle_rad)
    s = math.sin(angle_rad)
    t = 1 - c
    
    R = np.array([
        [t * ax * ax + c, t * ax * ay - s * az, t * ax * az + s * ay, 0],
        [t * ax * ay + s * az, t * ay * ay + c, t * ay * az - s * ax, 0],
        [t * ax * az - s * ay, t * ay * az + s * ax, t * az * az + c, 0],
        [0, 0, 0, 1]
    ], dtype=np.float64)
    
    return R


def apply_transformation(vertices: List[Point3D], matrix: np.ndarray) -> List[Point3D]:
    """Применяет матрицу преобразования к списку вершин."""
    transformed = []
    for vertex in vertices:
        x, y, z = vertex
        # Преобразуем в однородные координаты
        v = np.array([x, y, z, 1.0], dtype=np.float64)
        # Применяем преобразование
        v_transformed = matrix @ v
        # Возвращаем в обычные координаты
        transformed.append((v_transformed[0], v_transformed[1], v_transformed[2]))
    return transformed


def orthographic_projection_xy(vertices: List[Point3D]) -> List[Tuple[float, float]]:
    """Ортографическая проекция на плоскость Oxy (z отбрасывается)."""
    return [(x, y) for x, y, z in vertices]


def orthographic_projection_xz(vertices: List[Point3D]) -> List[Tuple[float, float]]:
    """Ортографическая проекция на плоскость Oxz (y отбрасывается)."""
    return [(x, z) for x, y, z in vertices]


def orthographic_projection_yz(vertices: List[Point3D]) -> List[Tuple[float, float]]:
    """Ортографическая проекция на плоскость Oyz (x отбрасывается)."""
    return [(y, z) for x, y, z in vertices]

